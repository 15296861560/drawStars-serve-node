/**
 * 题目发牌器：同一实例内缓存最近 8 题防连重
 * @param {string} seedKey 防重域（同一场对局传 session.id）
 */
function createTodDealer(seedKey) {
  const recent = { truth: [], dare: [] } // 每类各缓存 8 题
  const NO_REPEAT = 8

  function drawFrom(pool, kind) {
    let fresh = pool.filter((q) => recent[kind].indexOf(q) === -1)
    if (!fresh.length) {
      recent[kind] = [] // 本轮题荒 → 重新洗牌（PRD 异常处理）
      fresh = pool.slice()
    }
    const q = fresh[Math.floor(Math.random() * fresh.length)]
    recent[kind].push(q)
    if (recent[kind].length > NO_REPEAT) recent[kind].shift()
    return q
  }

  return {
    /**
     * @param {Object} opts { level, kind: 'truth'|'dare', themeTags: [] }
     * 玩法 B：themeTags 非空时仅从主题池抽取；否则按分级池抽取
     */
    next(opts) {
      const o = opts || {}
      const kind = o.kind === 'dare' ? 'dare' : 'truth'
      const themes = o.themeTags || []
      let pool = []
      themes.forEach((t) => {
        const tp = THEME_POOLS[t]
        if (tp && tp[kind]) pool = pool.concat(tp[kind])
      })
      if (!pool.length) {
        const lp = LEVEL_POOLS[o.level] || LEVEL_POOLS.gentle
        pool = lp[kind]
      }
      return {
        kind,
        level: o.level || 'gentle',
        themes: themes.slice(),
        text: drawFrom(pool, kind),
      }
    },
  }
}

module.exports = { LEVEL_POOLS, THEME_POOLS, createTodDealer }
